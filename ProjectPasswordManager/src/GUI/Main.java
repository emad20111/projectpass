private void initTable() {
    
    tableModel = (DefaultTableModel) ptable.getModel();
    
        ptable.getColumnModel().getColumn(0).setMinWidth(0);
        ptable.getColumnModel().getColumn(0).setMaxWidth(0);
    }
    
    private void loadEntries() {
        tableModel.setRowCount(0);
        List<PasswordEntry> entries = operations.getAllEntries();
        
        for (PasswordEntry entry : entries) {
            tableModel.addRow(new Object[]{
                entry.getId(),
                entry.getServiceName(),
                entry.getUsername(),
                operations.getDecryptedPassword(entry.getId()),
                entry.getUrl(),
                entry.getNotes()
            });
        }
    }
