    private void checkStrengthButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_checkStrengthButtonActionPerformed
         String password = new String(passwordField.getPassword());
        int strength = operations.validatePasswordStrength(password);
        String message;
        message = switch (strength) {
             case 4 -> "قوية جداً";
             case 3 -> "قوية";
             case 2 -> "متوسطة";
             case 1 -> "ضعيفة";
             default -> "سيئة جداً";
         };
        JOptionPane.showMessageDialog(null, "قوة كلمة المرور: " + message);
    }//GEN-LAST:event_checkStrengthButtonActionPerformed

    private void updateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateButtonActionPerformed
        int selectedRow = ptable.getSelectedRow();
    if (selectedRow != -1) {
        int entryId = (int) tableModel.getValueAt(selectedRow, 0);
        String service = serviceField.getText();
        String username = usernameField.getText();
        String password = new String(passwordField.getPassword());
        String url = urlField.getText();
        String notes = notesField.getText();

        if (operations.updateEntry(entryId, service, username, password, url, notes)) {
            loadEntries(); 
            clearFields();
            JOptionPane.showMessageDialog(this, "تم التحديث بنجاح");
        } else {
            JOptionPane.showMessageDialog(this, "فشل التحديث");
        }
    } else {
        JOptionPane.showMessageDialog(this, "الرجاء اختيار صف من الجدول");
    }
    }//GEN-LAST:event_updateButtonActionPerformed

